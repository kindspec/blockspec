"""Generate REHEARSALS.md: one row per rehearsal run in the rehearsal
directory, failures included, read from each run's own files.

Per run: the export, its packet count, how many distinct packets tiers.jsonl
answered, each plant's q1-q4 against its expectation, and whether prereg 2
§7.3's void rule (q3/q4 mismatch, wrong side of B/C, untiered) would fire.

usage: python3 -I -S -B rehearsal_table.py <rehearsal dir> <out.md> [sha12=label ...]
"""
import glob
import hashlib
import json
import os
import sys

root, out = sys.argv[1:3]
NAMES = dict(a.split("=", 1) for a in sys.argv[3:])  # plant-set sha prefix -> label
QUAL = {"A": True, "B": True, "C": False}


def tier(a):
    if a.get("unplaceable"):
        return "U"
    return "A" if a["q2"] == "yes" else ("B" if a["q1"] == "yes" else "C")


def key_for(label):
    """{packet name: (plant label, expected)} for an export label."""
    p = os.path.join(root, f"export-{label}-key.json")
    if os.path.exists(p):
        k = json.load(open(p))
        sha = k.get("plants_py_sha256", "")[:12]
        return {n: (v["plant"], v["expected"]) for n, v in k["packets"].items() if v["plant"]}, \
            NAMES.get(sha, sha)
    if label.startswith("p30-"):
        k = json.load(open(os.path.join(root, "plants-p30-key.json")))
        return {n: (v["plant"] + "(prereg2)", dict(v["expected"], tier={"P-A": "A", "P-B": "B", "P-C": "C"}[v["plant"]]))
                for n, v in k.items() if v["run"] == int(label[4:])}, "prereg2-B"
    k = json.load(open(os.path.join(root, "rehearsal-key.json")))["packets"]
    return {n: (v["key"].split(":")[1], v["expected"]) for n, v in k.items() if v["expected"]}, "synthetic-R"


rows = []
for run in sorted(glob.glob(os.path.join(root, "run-*")), key=lambda p: p.rsplit("-", 1)[1]):
    info = dict(ln.split(" ", 1) for ln in open(os.path.join(run, "run-info.txt")).read().splitlines() if " " in ln)
    exp_dir = info["export"].split(" ")[0]
    label = os.path.basename(exp_dir)[len("export-"):]
    n_export = len(os.listdir(os.path.join(exp_dir, "packets")))
    tp = os.path.join(run, "state", "tier-work-1", "tiers.jsonl")
    ans, bad = {}, 0
    if os.path.exists(tp):
        for ln in open(tp, encoding="utf-8"):
            if not ln.strip():
                continue
            try:
                o = json.loads(ln)
                ans.setdefault(o["packet"], o)
            except (ValueError, KeyError, TypeError):
                bad += 1
    names = set(os.listdir(os.path.join(exp_dir, "packets")))
    answered = len(set(ans) & names)
    plants, pset = key_for(label)
    cells, all4, void = [], True, []
    for name, (pl, e) in sorted(plants.items(), key=lambda x: x[1][0]):
        a = ans.get(name)
        if a is None:
            cells.append(f"{pl}: untiered")
            all4 = False
            void.append(f"{pl} untiered")
            continue
        got = "".join("y" if a[q] == "yes" else "n" for q in ("q1", "q2", "q3", "q4"))
        want = "".join("y" if e[q] == "yes" else "n" for q in ("q1", "q2", "q3", "q4"))
        ok = got == want and not a.get("unplaceable")
        all4 &= ok
        cells.append(f"{pl} {got}" + ("" if ok else f" (want {want})"))
        if QUAL.get(tier(a), False) != QUAL[e["tier"]]:
            void.append(f"{pl} tier {tier(a)}")
        for q in ("q3", "q4"):
            if a[q] != e[q]:
                void.append(f"{pl} {q}")
    psha = info.get("prompt_sha256", "")[:12] or "prereg2-A"
    mcp = "?"
    for tf in glob.glob(os.path.join(run, "transcripts", "*.txt")):
        for ln in open(tf, encoding="utf-8", errors="replace"):
            i = ln.find('"mcp_servers":')
            if i >= 0 and '"subtype":"init"' in ln:
                mcp = "none" if '"mcp_servers":[]' in ln else "PENDING" if '"status":"pending"' in ln[i:i + 300] else "listed"
                break
        if mcp != "?":
            break
    rows.append({"run": os.path.basename(run), "label": label, "start": info.get("start_utc", ""),
                 "wall": info.get("wall_seconds", "?"), "exit": info.get("tier_run_exit", "?"),
                 "packets": n_export, "answered": answered, "bad": bad, "plants": "; ".join(cells), "mcp": mcp,
                 "all4": all4, "void": void, "prompt": psha, "pset": pset})

L = ["# Tiering rehearsals", "",
     "Generated by `rehearsal_table.py` from each run directory under the rehearsal",
     "directory. Do not edit by hand. Answers are q1–q4 as y/n; `want` is the",
     "expected answer where it differs. `void` applies prereg 2 §7.3's rule: a",
     "plant's q3 or q4 differs, its tier crosses the B/C line, or it is untiered.",
     "`all 4` is the stricter bar this draft uses: every plant's q1–q4 as expected.",
     "`MCP at init` is the agent's MCP server list in its init event: `none`, or `PENDING` (a connector listed, never used).",
     "`prompt` is the sha256 prefix of the PROMPT.md sent (`prereg2-A` = prereg 2's",
     "Appendix A). `plants` names the plant set: `prereg2-B` is Appendix B, `synthetic-R`",
     "is build.py's R-* plants, otherwise a label for the sha256 of the plants module:", ""] + \
    [f"- `{v}`: plants module sha256 prefix `{k}`" for k, v in NAMES.items()] + ["",
     "| run | export | start (UTC) | wall s | exit | packets | answered | plant set | prompt | plant answers | all 4 | void | MCP at init |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    cov = f"{r['answered']}" + ("" if r["answered"] == r["packets"] else " **MISSED**") + (f", {r['bad']} bad" if r["bad"] else "")
    L.append(f"| {r['run']} | {r['label']} | {r['start']} | {r['wall']} | {r['exit']} | {r['packets']} | {cov} | "
             f"{r['pset']} | {r['prompt']} | {r['plants']} | {'yes' if r['all4'] else 'no'} | "
             f"{'VOID: ' + ', '.join(r['void']) if r['void'] else 'no'} | {r['mcp']} |")
L += ["", "## Summary by plant set and prompt", ""]
groups = {}
for r in rows:
    groups.setdefault((r["pset"], r["prompt"], r["packets"]), []).append(r)
L += ["| plant set | prompt | packets per run | runs | all 4 as expected | would void | full coverage |", "|---|---|---|---|---|---|---|"]
for (ps, pr, npk), rs in groups.items():
    L.append(f"| {ps} | {pr} | {npk} | {len(rs)} | {sum(r['all4'] for r in rs)} | {sum(bool(r['void']) for r in rs)} | "
             f"{sum(r['answered'] == r['packets'] for r in rs)} |")
text = "\n".join(L) + "\n"
open(out, "w").write(text)
print(text)
print("sha256", hashlib.sha256(text.encode()).hexdigest())
